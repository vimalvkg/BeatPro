// Arabic for the app. Texts are matched exactly first, then by the patterns
// below (texts with numbers, amounts and names in them). Digits stay Western
// (1 2 3), as UAE shops and Odoo write them.

final _letters = RegExp('[A-Za-z]');

/// [s] in Arabic. A text with no Arabic is returned as it is, and added to
/// [misses] when given.
String translateAr(String s, {Set<String>? misses}) {
  final r = _tr(s, misses);
  if (r != null) return r;
  misses?.add(s);
  return _units(s);
}

String? _tr(String s, Set<String>? misses) {
  if (s.trim().isEmpty) return s;
  final exact = _exact[s] ?? _upper[s];
  if (exact != null) return exact;
  final t = s.trim();
  if (t != s) {
    final x = _tr(t, misses);
    if (x != null) return s.replaceFirst(t, x);
  }
  if (t.endsWith('…') && _exact[t.substring(0, t.length - 1)] != null) return '${_exact[t.substring(0, t.length - 1)]}…';
  // A text in parts (`3 of 4 visited · 2.5 km`) is translated part by part,
  // unless a pattern is written for the whole of it.
  final parts = s.contains(' · ');
  for (final (re, template) in _patterns) {
    if (parts && !re.pattern.contains('·')) continue;
    final m = re.firstMatch(s);
    if (m == null) continue;
    return template.replaceAllMapped(RegExp(r'\$(\d)'), (g) {
      final group = m.group(int.parse(g.group(1)!)) ?? '';
      return _tr(group, null) ?? _units(group);
    });
  }
  if (parts) {
    return s.split(' · ').map((p) {
      final x = _tr(p, misses);
      if (x == null && _letters.hasMatch(p)) misses?.add(p);
      return x ?? _units(p);
    }).join(' · ');
  }
  if (!_letters.hasMatch(s)) return s;
  return null;
}

/// `3 cs + 5 pc` in Arabic, inside texts that are otherwise names.
String _units(String s) => s
    .replaceAllMapped(RegExp(r'(\d) cs\b'), (m) => '${m.group(1)} كرتون')
    .replaceAllMapped(RegExp(r'(\d) pc\b'), (m) => '${m.group(1)} حبة')
    .replaceAllMapped(RegExp(r'(\d) km\b'), (m) => '${m.group(1)} كم');

